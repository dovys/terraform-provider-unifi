package unifi

import (
	"context"
	"fmt"
)

const wlanconfType = "wlanconf"

// WLANConf is a legacy `/rest/wlanconf` document — a Wi-Fi SSID and its
// security/radio settings. Field names mirror the controller wire shape exactly
// (confirmed against a live UCG Max). Pointers + omitempty give three-state
// semantics on GET-merge-PUT: nil = leave the controller's value, set = write
// it (including an explicit false/0). Exotic fields not modeled here (schedules,
// hotspot 2.0 detail, 6 GHz fine-tuning) are carried through untouched by
// GET-merge-PUT.
type WLANConf struct {
	ID                string `json:"_id,omitempty"`                // controller object ID (Mongo _id); the resource import key
	SiteID            string `json:"site_id,omitempty"`            // owning site UUID (controller-assigned)
	Name              string `json:"name"`                         // the SSID
	Enabled           *bool  `json:"enabled,omitempty"`            // whether the SSID is broadcast
	NetworkConfID     string `json:"networkconf_id,omitempty"`     // the network/VLAN this SSID bridges onto (networkconf _id)
	SettingPreference string `json:"setting_preference,omitempty"` // auto | manual controller toggle (read-only here)
	ExternalID        string `json:"external_id,omitempty"`        // external/system reference (computed)
	ShortID           string `json:"short_id,omitempty"`           // controller-internal short id (computed)

	// AP coverage and user group.
	APGroupIDs  []string `json:"ap_group_ids,omitempty"`  // AP groups this SSID broadcasts on (apgroup _ids)
	APGroupMode string   `json:"ap_group_mode,omitempty"` // all | exclude — how ap_group_ids is interpreted
	UserGroupID string   `json:"usergroup_id,omitempty"`  // bandwidth/user group applied to clients

	// Security. security selects the suite; the WPA3 flags refine WPA2/WPA3.
	Security        string `json:"security,omitempty"`          // open | wpapsk | wpaeap | osen
	WPAMode         string `json:"wpa_mode,omitempty"`          // wpa2 | wpa3 | … (cipher/mode)
	WPA3Support     *bool  `json:"wpa3_support,omitempty"`      // offer WPA3 alongside WPA2
	WPA3Transition  *bool  `json:"wpa3_transition,omitempty"`   // WPA2/WPA3 transition mode
	WPA3Enhanced192 *bool  `json:"wpa3_enhanced_192,omitempty"` // WPA3 Enterprise 192-bit
	PMFMode         string `json:"pmf_mode,omitempty"`          // protected management frames: disabled | optional | required

	// Passphrase. x_passphrase is the PSK (Sensitive); the controller does echo
	// it on read, so it round-trips into state.
	XPassphrase             string `json:"x_passphrase,omitempty"`             // WPA pre-shared key (sensitive)
	PassphraseAutogenerated *bool  `json:"passphrase_autogenerated,omitempty"` // PSK was auto-generated by the controller
	XIAPPKey                string `json:"x_iapp_key,omitempty"`               // inter-AP roaming key (sensitive, controller-managed)

	// Per-client PSKs (PPSK): each key maps clients to a network/VLAN.
	PrivatePresharedKeysEnabled *bool                 `json:"private_preshared_keys_enabled,omitempty"` // enable per-client PSKs
	PrivatePresharedKeys        []PrivatePresharedKey `json:"private_preshared_keys,omitempty"`         // the PPSK entries

	// Radio bands.
	WLANBand  string   `json:"wlan_band,omitempty"`  // legacy single-band selector (2g | 5g | both)
	WLANBands []string `json:"wlan_bands,omitempty"` // bands to broadcast on: 2g | 5g | 6g

	// Visibility / isolation / client behavior.
	IsGuest                     *bool `json:"is_guest,omitempty"`                        // apply guest policies (captive portal, isolation)
	HideSSID                    *bool `json:"hide_ssid,omitempty"`                       // don't broadcast the SSID name
	L2Isolation                 *bool `json:"l2_isolation,omitempty"`                    // block client-to-client traffic
	ProxyARP                    *bool `json:"proxy_arp,omitempty"`                       // answer ARP on behalf of clients
	BSSTransition               *bool `json:"bss_transition,omitempty"`                  // 802.11v BSS transition
	UAPSDEnabled                *bool `json:"uapsd_enabled,omitempty"`                   // WMM power save (U-APSD)
	FastRoamingEnabled          *bool `json:"fast_roaming_enabled,omitempty"`            // 802.11r fast roaming
	MCastEnhanceEnabled         *bool `json:"mcastenhance_enabled,omitempty"`            // multicast enhancement (IGMP→unicast)
	AdvertiseDeviceNameInBeacon *bool `json:"advertise_device_name_in_beacon,omitempty"` // include AP name in beacons
	No2GHzOUI                   *bool `json:"no2ghz_oui,omitempty"`                      // disable 2.4 GHz for known 5 GHz-capable OUIs
	MLOEnabled                  *bool `json:"mlo_enabled,omitempty"`                     // Wi-Fi 7 multi-link operation

	// MAC address filter.
	MACFilterEnabled *bool    `json:"mac_filter_enabled,omitempty"` // enable the MAC allow/deny list
	MACFilterPolicy  string   `json:"mac_filter_policy,omitempty"`  // allow | deny
	MACFilterList    []string `json:"mac_filter_list,omitempty"`    // the MAC addresses

	// Broadcast/multicast filter.
	BCFilterEnabled *bool    `json:"bc_filter_enabled,omitempty"` // enable broadcast/multicast filtering
	BCFilterList    []string `json:"bc_filter_list,omitempty"`    // allowed broadcast MACs

	// Minimum data rate control (ng = 2.4 GHz, na = 5 GHz).
	MinrateSettingPreference  string `json:"minrate_setting_preference,omitempty"` // auto | manual
	MinrateNGEnabled          *bool  `json:"minrate_ng_enabled,omitempty"`         // enforce a 2.4 GHz minimum rate
	MinrateNGDataRateKbps     *int   `json:"minrate_ng_data_rate_kbps,omitempty"`  // 2.4 GHz minimum rate (kbps)
	MinrateNGAdvertisingRates *bool  `json:"minrate_ng_advertising_rates,omitempty"`
	MinrateNAEnabled          *bool  `json:"minrate_na_enabled,omitempty"`        // enforce a 5 GHz minimum rate
	MinrateNADataRateKbps     *int   `json:"minrate_na_data_rate_kbps,omitempty"` // 5 GHz minimum rate (kbps)
	MinrateNAAdvertisingRates *bool  `json:"minrate_na_advertising_rates,omitempty"`

	// DTIM beacon period.
	DTIMMode string `json:"dtim_mode,omitempty"` // default | custom
	DTIMNG   *int   `json:"dtim_ng,omitempty"`   // 2.4 GHz DTIM period
	DTIMNA   *int   `json:"dtim_na,omitempty"`   // 5 GHz DTIM period
	DTIM6E   *int   `json:"dtim_6e,omitempty"`   // 6 GHz DTIM period

	// Roaming assistant (kick weak clients below an RSSI threshold).
	RoamingAssistantNAEnabled *bool `json:"roaming_assistant_na_enabled,omitempty"`
	RoamingAssistantNARSSI    *int  `json:"roaming_assistant_na_rssi,omitempty"`
	RoamingAssistant6EEnabled *bool `json:"roaming_assistant_6e_enabled,omitempty"`
	RoamingAssistant6ERSSI    *int  `json:"roaming_assistant_6e_rssi,omitempty"`

	// RADIUS / advanced.
	RADIUSMACAuthEnabled *bool  `json:"radius_mac_auth_enabled,omitempty"` // MAC-based RADIUS auth
	RADIUSDASEnabled     *bool  `json:"radius_das_enabled,omitempty"`      // RADIUS dynamic authorization (CoA/DAS)
	GroupRekey           *int   `json:"group_rekey,omitempty"`             // GTK rekey interval (seconds)
	Hotspot2confEnabled  *bool  `json:"hotspot2conf_enabled,omitempty"`    // Hotspot 2.0 / Passpoint
	EnhancedIOT          *bool  `json:"enhanced_iot,omitempty"`            // enhanced IoT connectivity
	DNSAssistanceMode    string `json:"dns_assistance_mode,omitempty"`     // private DNS assistance mode
	MDNSProxyMode        string `json:"mdns_proxy_mode,omitempty"`         // mDNS proxy behavior
	IAPPEnabled          *bool  `json:"iapp_enabled,omitempty"`            // inter-AP protocol (legacy roaming)
}

// PrivatePresharedKey is one per-client PSK entry on a WLAN. The password is the
// client's key (Sensitive); networkconf_id places matching clients on a VLAN.
type PrivatePresharedKey struct {
	Password      string `json:"password"`                 // the per-client PSK (sensitive)
	NetworkConfID string `json:"networkconf_id,omitempty"` // VLAN/network clients using this key land on
}

// WLAN CRUD (legacy /rest/wlanconf). Update is GET-merge-PUT so
// controller-managed fields survive.

func (c *client) ListWLANs(ctx context.Context) ([]WLANConf, error) {
	return legacyList[WLANConf](ctx, c, wlanconfType)
}

func (c *client) GetWLAN(ctx context.Context, id string) (*WLANConf, error) {
	return legacyGet[WLANConf](ctx, c, wlanconfType, id)
}

func (c *client) CreateWLAN(ctx context.Context, w *WLANConf) (*WLANConf, error) {
	return legacyCreate[WLANConf](ctx, c, wlanconfType, w)
}

func (c *client) UpdateWLAN(ctx context.Context, w *WLANConf) (*WLANConf, error) {
	if w.ID == "" {
		return nil, fmt.Errorf("UpdateWLAN: missing id")
	}
	return legacyMergePut[WLANConf](ctx, c, wlanconfType, w.ID, w)
}

func (c *client) DeleteWLAN(ctx context.Context, id string) error {
	return legacyDelete(ctx, c, wlanconfType, id)
}
