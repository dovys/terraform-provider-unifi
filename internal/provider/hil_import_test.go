//go:build hil

package provider

// Rung-B helper: discovers the live Network objects and writes Terraform
// `import {}` blocks to $HIL_IMPORTS_OUT, which test/hil/run.sh feeds to
// `tofu plan -generate-config-out` for the import -> clean-plan regression.
//
// READ-ONLY: GETs + the session-login POST only. Build-tagged `hil` (never in
// `make test`); skips unless HIL_IMPORTS_OUT is set. The output lists real
// controller object IDs, so run.sh writes it to a gitignored path.

import (
	"context"
	"fmt"
	"os"
	"strings"
	"testing"
	"time"

	"github.com/dovys/terraform-provider-unifi/internal/unifi"
)

func TestHILGenerateImports(t *testing.T) {
	out := os.Getenv("HIL_IMPORTS_OUT")
	if out == "" {
		t.Skip("set HIL_IMPORTS_OUT to generate import blocks (Rung B)")
	}
	host := os.Getenv("UNIFI_HOST")
	if host == "" {
		t.Skip("set UNIFI_HOST")
	}
	user, pass := os.Getenv("UNIFI_USERNAME"), os.Getenv("UNIFI_PASSWORD")
	if user == "" || pass == "" {
		t.Fatal("set UNIFI_USERNAME and UNIFI_PASSWORD (the network-admin local admin)")
	}

	ctx, cancel := context.WithTimeout(context.Background(), 120*time.Second)
	defer cancel()

	c, err := unifi.NewClient(ctx, unifi.Config{
		Host:          host,
		Username:      user,
		Password:      pass,
		Site:          envOr("UNIFI_SITE", "default"),
		AllowInsecure: strings.EqualFold(os.Getenv("UNIFI_ALLOW_INSECURE"), "true") || os.Getenv("UNIFI_ALLOW_INSECURE") == "1",
	})
	if err != nil {
		t.Fatalf("login/connect: %v", err)
	}
	n := c.Network()

	var b strings.Builder
	b.WriteString("# GENERATED by TestHILGenerateImports — DO NOT COMMIT (real controller object IDs).\n")
	b.WriteString("# Rung-B import -> clean-plan regression. Read-only discovery.\n\n")
	count := 0
	emit := func(rtype, name, id string) {
		if id == "" {
			return
		}
		fmt.Fprintf(&b, "import {\n  to = %s.%s\n  id = %q\n}\n\n", rtype, name, id)
		count++
	}
	d := func(p *string) string {
		if p == nil {
			return ""
		}
		return *p
	}

	// _id-passthrough resources that exist live. (unifi_network_device is excluded
	// below — its telemetry is runtime-volatile, so plan-only can't be clean.)
	recs, err := n.DNS().Records().List(ctx)
	hilMust(t, err, "dns")
	for i, r := range recs {
		emit("unifi_network_dns_record", fmt.Sprintf("dns%d", i), d(r.UnderscoreId))
	}
	frs, err := n.Firewall().Rules().List(ctx)
	hilMust(t, err, "firewall_rule")
	for i, r := range frs {
		emit("unifi_network_firewall_rule", fmt.Sprintf("fw%d", i), d(r.UnderscoreId))
	}
	ugs, err := n.UserGroups().List(ctx)
	hilMust(t, err, "user_group")
	for i, r := range ugs {
		emit("unifi_network_user_group", fmt.Sprintf("ug%d", i), d(r.UnderscoreId))
	}
	wls, err := n.WiFi().WLANs().List(ctx)
	hilMust(t, err, "wlan")
	for i, r := range wls {
		emit("unifi_network_wlan", fmt.Sprintf("wlan%d", i), d(r.UnderscoreId))
	}
	wgs, err := n.WiFi().WLANGroups().List(ctx)
	hilMust(t, err, "wlan_group")
	for i, r := range wgs {
		emit("unifi_network_wlan_group", fmt.Sprintf("wg%d", i), d(r.UnderscoreId))
	}
	// radius_profile is intentionally NOT auto-imported: auth_servers[].x_secret
	// is Required but write-only (the controller never echoes it on read), so
	// -generate-config-out can't produce valid config. It imports fine with a
	// hand-written config that supplies the secret.
	ags, err := n.WiFi().APGroups().List(ctx)
	hilMust(t, err, "ap_group")
	for i, r := range ags {
		emit("unifi_network_ap_group", fmt.Sprintf("ap%d", i), d(r.UnderscoreId))
	}
	// unifi_network_device is intentionally NOT in this plan-only set: its computed
	// read-only telemetry (ip, state) is runtime-volatile, so a generate-config-out
	// plan always reports it "known after apply" — never clean without an apply +
	// second plan. Rung A (hil_read_test.go) already verifies device read/decode.
	//
	// dhcp_reservation: the users carrying a fixed-IP reservation (use_fixedip).
	users, err := n.Clients().Users().List(ctx)
	hilMust(t, err, "clients_users")
	ri := 0
	for _, u := range users {
		if u.UseFixedip != nil && *u.UseFixedip {
			emit("unifi_network_dhcp_reservation", fmt.Sprintf("res%d", ri), d(u.UnderscoreId))
			ri++
		}
	}
	// networkconf splits on purpose: purpose=wan -> unifi_network_wan, else unifi_network_network.
	nets, err := n.Networks().List(ctx)
	hilMust(t, err, "networks")
	for i, nw := range nets {
		if nw.Purpose != nil && string(*nw.Purpose) == "wan" {
			// PPPoE WANs carry a write-only x_wan_password: -generate-config-out
			// nulls sensitive values, so the round-trip can't be clean — skip,
			// like radius_profile. (DHCP/static WANs round-trip fine.)
			if nw.WanType != nil && string(*nw.WanType) == "pppoe" {
				continue
			}
			emit("unifi_network_wan", fmt.Sprintf("wan%d", i), d(nw.UnderscoreId))
		} else {
			emit("unifi_network_network", fmt.Sprintf("net%d", i), d(nw.UnderscoreId))
		}
	}

	if err := os.WriteFile(out, []byte(b.String()), 0o644); err != nil {
		t.Fatalf("write %s: %v", out, err)
	}
	t.Logf("wrote %d import blocks to %s", count, out)
}

func hilMust(t *testing.T, err error, what string) {
	t.Helper()
	if err != nil {
		t.Fatalf("list %s: %v", what, err)
	}
}
